/** A department's name in the buyer's language; English is the name the API sent. */
export function departmentName(d: { id: string; name: string }, lang: Lang): string {
  if (lang === "en") return d.name;
  const map = DEPARTMENT_NAME[lang];
  return map[d.id.replace(/^d/, "")] ?? (d.name === "Other" ? map.other : d.name);
}
